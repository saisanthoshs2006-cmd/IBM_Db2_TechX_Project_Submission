"""Guard routes: status, offline lint, and prepare-only check of human-written SQL."""
from __future__ import annotations

from fastapi import APIRouter, Request

from db2intel.api.errors import error, log, public_reason, respond, sanitize
from db2intel.api.schemas import SqlRequest
from db2intel.guard.lexer import GuardViolation
from db2intel.guard.parser import guard_sql
from db2intel.guard.worker import (
    AI_SQL_CHECK_ENABLED, ORIGIN_HUMAN, AISqlNotAllowed, Degraded, PoolBusy, WorkerFailed, WorkerStartError,
    WorkerTimeout,
)

router = APIRouter(prefix="/api/v1/guard")


def _lint_payload(guarded) -> dict:
    return {
        "status": "LINT_APPROVED", "code": "lint_approved", "reason": "passed the static SQL guard",
        "sql": guarded.text, "tables": [list(t) for t in guarded.tables], "row_cap": guarded.row_cap,
        "cap_action": guarded.cap_action, "functions": list(guarded.functions),
    }


def _lint(state, sql: str):
    try:
        return guard_sql(sql, state.lint_schemas, state.api.max_rows), None
    except GuardViolation as exc:
        return None, {"status": "BLOCKED", "code": exc.code, "reason": sanitize(str(exc))}


@router.get("/status")
def status(request: Request):
    state = request.app.state.ctx
    pool = state.pool.status() if state.pool is not None else None
    return respond(200, {
        "status": "DEGRADED" if pool and pool["degraded"] else "OK",
        "pool": pool,
        "guard_check_available": state.pool is not None,
        "guard_disabled_reason": state.guard_disabled_reason,
        "ai_sql_check_enabled": AI_SQL_CHECK_ENABLED,
        "execution_enabled": False,
        "audit": "disabled",
        "lint_schemas": sorted(state.lint_schemas),
        "max_rows": state.api.max_rows,
    })


@router.post("/lint")
def lint(body: SqlRequest, request: Request):
    guarded, blocked = _lint(request.app.state.ctx, body.sql)
    payload = blocked if blocked else _lint_payload(guarded)
    return respond(200, payload, db_checked=False)


@router.post("/check")
def check(body: SqlRequest, request: Request):
    """Static lint, then (for human-written SQL only) a prepare-only check in a guard worker.

    The query is never executed: the worker prepares, explains and rolls back.
    """
    state = request.app.state.ctx
    guarded, blocked = _lint(state, body.sql)
    if blocked:
        return respond(200, blocked, db_checked=False)
    if guarded.text in state.registry:
        return error(403, "ai_sql_not_checkable",
                     "this SQL was generated by the model; AI-generated SQL is not prepared until gate G4 is approved")
    if state.pool is None:
        return error(503, "guard_disabled", "the database guard check is not enabled in this process")
    try:
        decision = state.pool.check(body.sql, origin=ORIGIN_HUMAN)
    except AISqlNotAllowed as exc:
        return error(403, exc.code, str(exc))
    except Degraded as exc:
        return error(503, exc.code, f"the guard is degraded and refuses checks until restart: {exc}")
    except PoolBusy as exc:
        response = error(503, exc.code, str(exc))
        response.headers["Retry-After"] = "2"
        return response
    except WorkerTimeout as exc:
        return error(504, exc.code, str(exc))
    except (WorkerStartError, WorkerFailed) as exc:
        log.warning("guard check failed: %s", sanitize(exc))
        return error(503, exc.code, str(exc))
    except ValueError as exc:
        return error(422, "invalid_sql", str(exc))
    return respond(200, {
        "status": decision["status"],
        "code": decision["code"],
        "reason": public_reason(decision["reason"], decision["sqlstate"]),
        "sql": decision["sql"],
        "estimated_cost": decision["estimated_cost"],
        "explain_cost": decision["explain_cost"],
        "objects": [list(o) for o in decision["objects"]],
        "plan": [list(p) for p in decision["plan"]],
        "sqlstate": decision["sqlstate"],
        "request_id": decision["request_id"],
    }, db_checked=True)
