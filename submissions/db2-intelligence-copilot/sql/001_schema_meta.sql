-- =============================================================================
-- 001_schema_meta.sql  -  Db2 Intelligence application metadata (schema DB2INTEL)
-- Target : IBM Db2 12.1.2+ (native VECTOR type). Developed against 12.1.5.
-- Scope  : creates objects ONLY in schema DB2INTEL. Never references DB2INST1.
-- Apply  : python -m db2intel.db.migrate up   (one transaction, ledger, checksum)
-- Order  : 001_schema_meta.sql -> 002_demo_data.sql. Teardown is never part of init.
-- Vectors: VECTOR(768, FLOAT32) = Ollama nomic-embed-text output size. A 768-dim
--          FLOAT32 vector is 3072 bytes, so vectors live in narrow tables of their
--          own to stay inside the 4005-byte row limit of TESTDB's 4K pages.
-- Syntax : statements end with ';'. No ';' or '--' inside string literals.
-- =============================================================================

CREATE SCHEMA DB2INTEL;

-- Migration ledger. One row per applied script. Written in the same transaction
-- as the script itself, so ledger and objects are always consistent.
CREATE TABLE DB2INTEL.SCHEMA_MIGRATION (
    MIGRATION_ID     VARCHAR(100)  NOT NULL,
    CHECKSUM_SHA256  CHAR(64)      NOT NULL,
    APPLIED_AT       TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    APPLIED_BY       VARCHAR(128)  NOT NULL DEFAULT USER,
    EXECUTION_MS     INTEGER,
    CONSTRAINT PK_SCHEMA_MIGRATION PRIMARY KEY (MIGRATION_ID),
    CONSTRAINT CK_SCHEMA_MIGRATION_MS CHECK (EXECUTION_MS IS NULL OR EXECUTION_MS >= 0)
);

-- Runtime settings. embedding.dimension records the VECTOR size this schema was
-- built with. The application refuses to start if its embedding model differs.
CREATE TABLE DB2INTEL.APP_SETTING (
    SETTING_KEY    VARCHAR(64)   NOT NULL,
    SETTING_VALUE  VARCHAR(512)  NOT NULL,
    VALUE_TYPE     VARCHAR(8)    NOT NULL DEFAULT 'STRING',
    DESCRIPTION    VARCHAR(254),
    UPDATED_AT     TIMESTAMP     NOT NULL GENERATED ALWAYS FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP,
    CONSTRAINT PK_APP_SETTING PRIMARY KEY (SETTING_KEY),
    CONSTRAINT CK_APP_SETTING_TYPE CHECK (VALUE_TYPE IN ('STRING', 'INTEGER', 'DECIMAL', 'BOOLEAN'))
);

-- Allow-list of schemas the copilot may read. TESTDB.DB2INST1 can never be registered.
CREATE TABLE DB2INTEL.DATA_SOURCE (
    SOURCE_ID      INTEGER       NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    SOURCE_NAME    VARCHAR(64)   NOT NULL,
    DATABASE_NAME  VARCHAR(8)    NOT NULL,
    SCHEMA_NAME    VARCHAR(128)  NOT NULL,
    ACCESS_MODE    VARCHAR(10)   NOT NULL DEFAULT 'READ_ONLY',
    IS_ENABLED     SMALLINT      NOT NULL DEFAULT 1,
    DESCRIPTION    VARCHAR(254),
    CREATED_AT     TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_DATA_SOURCE PRIMARY KEY (SOURCE_ID),
    CONSTRAINT UQ_DATA_SOURCE_NAME UNIQUE (SOURCE_NAME),
    CONSTRAINT UQ_DATA_SOURCE_TARGET UNIQUE (DATABASE_NAME, SCHEMA_NAME),
    CONSTRAINT CK_DATA_SOURCE_MODE CHECK (ACCESS_MODE = 'READ_ONLY'),
    CONSTRAINT CK_DATA_SOURCE_ENABLED CHECK (IS_ENABLED IN (0, 1)),
    CONSTRAINT CK_DATA_SOURCE_PROTECTED CHECK (NOT (DATABASE_NAME = 'TESTDB' AND SCHEMA_NAME = 'DB2INST1'))
);

-- Descriptions of tables, views and columns harvested from SYSCAT (text only).
CREATE TABLE DB2INTEL.SCHEMA_OBJECT (
    OBJECT_ID       BIGINT        NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    SOURCE_ID       INTEGER       NOT NULL,
    OBJECT_TYPE     VARCHAR(6)    NOT NULL,
    TABLE_SCHEMA    VARCHAR(128)  NOT NULL,
    TABLE_NAME      VARCHAR(128)  NOT NULL,
    COLUMN_NAME     VARCHAR(128)  NOT NULL DEFAULT '',
    DATA_TYPE       VARCHAR(64),
    CONTENT_TEXT    VARCHAR(1200) NOT NULL,
    CONTENT_SHA256  CHAR(64)      NOT NULL,
    CREATED_AT      TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    UPDATED_AT      TIMESTAMP     NOT NULL GENERATED ALWAYS FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP,
    CONSTRAINT PK_SCHEMA_OBJECT PRIMARY KEY (OBJECT_ID),
    CONSTRAINT UQ_SCHEMA_OBJECT UNIQUE (SOURCE_ID, OBJECT_TYPE, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME),
    CONSTRAINT FK_SCHEMA_OBJECT_SRC FOREIGN KEY (SOURCE_ID)
        REFERENCES DB2INTEL.DATA_SOURCE (SOURCE_ID) ON DELETE CASCADE,
    CONSTRAINT CK_SCHEMA_OBJECT_TYPE CHECK (OBJECT_TYPE IN ('TABLE', 'VIEW', 'COLUMN')),
    CONSTRAINT CK_SCHEMA_OBJECT_COL CHECK (
        (OBJECT_TYPE = 'COLUMN' AND COLUMN_NAME <> '') OR (OBJECT_TYPE <> 'COLUMN' AND COLUMN_NAME = ''))
);

CREATE INDEX DB2INTEL.IX_SCHEMA_OBJECT_TABLE ON DB2INTEL.SCHEMA_OBJECT (SOURCE_ID, TABLE_SCHEMA, TABLE_NAME);

-- One native Db2 VECTOR per (schema object, embedding model).
-- Searched with VECTOR_DISTANCE(EMBEDDING, VECTOR(?, 768, FLOAT32), COSINE).
CREATE TABLE DB2INTEL.SCHEMA_EMBEDDING (
    OBJECT_ID        BIGINT        NOT NULL,
    EMBEDDING_MODEL  VARCHAR(64)   NOT NULL,
    CONTENT_SHA256   CHAR(64)      NOT NULL,
    EMBEDDING        VECTOR(768, FLOAT32) NOT NULL,
    CREATED_AT       TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_SCHEMA_EMBEDDING PRIMARY KEY (OBJECT_ID, EMBEDDING_MODEL),
    CONSTRAINT FK_SCHEMA_EMBEDDING_OBJ FOREIGN KEY (OBJECT_ID)
        REFERENCES DB2INTEL.SCHEMA_OBJECT (OBJECT_ID) ON DELETE CASCADE
);

-- Append-only audit of every copilot request.
CREATE TABLE DB2INTEL.QUERY_AUDIT (
    AUDIT_ID           BIGINT        NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    REQUEST_ID         CHAR(36)      NOT NULL,
    SOURCE_ID          INTEGER,
    SESSION_ID         VARCHAR(64),
    USER_LABEL         VARCHAR(128),
    QUESTION           VARCHAR(1000) NOT NULL,
    GENERATED_SQL      CLOB(1M),
    STATUS             VARCHAR(16)   NOT NULL,
    BLOCK_REASON       VARCHAR(254),
    LLM_PROVIDER       VARCHAR(32),
    LLM_MODEL          VARCHAR(128),
    RETRIEVED_OBJECTS  VARCHAR(1000),
    VERIFIED_ID_USED   BIGINT,
    ESTIMATED_COST     DOUBLE,
    ROW_COUNT          INTEGER,
    LLM_MS             INTEGER,
    EXECUTION_MS       INTEGER,
    TOTAL_MS           INTEGER,
    ERROR_SQLSTATE     CHAR(5),
    ERROR_MESSAGE      VARCHAR(500),
    CREATED_AT         TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_QUERY_AUDIT PRIMARY KEY (AUDIT_ID),
    CONSTRAINT UQ_QUERY_AUDIT_REQUEST UNIQUE (REQUEST_ID),
    CONSTRAINT FK_QUERY_AUDIT_SRC FOREIGN KEY (SOURCE_ID)
        REFERENCES DB2INTEL.DATA_SOURCE (SOURCE_ID) ON DELETE SET NULL,
    CONSTRAINT CK_QUERY_AUDIT_STATUS CHECK (STATUS IN ('SUCCESS', 'BLOCKED', 'COST_REJECTED', 'ERROR', 'NO_SQL')),
    CONSTRAINT CK_QUERY_AUDIT_COST CHECK (ESTIMATED_COST IS NULL OR ESTIMATED_COST >= 0),
    CONSTRAINT CK_QUERY_AUDIT_ROWS CHECK (ROW_COUNT IS NULL OR ROW_COUNT >= 0),
    CONSTRAINT CK_QUERY_AUDIT_TIMES CHECK (
        (LLM_MS IS NULL OR LLM_MS >= 0) AND (EXECUTION_MS IS NULL OR EXECUTION_MS >= 0)
        AND (TOTAL_MS IS NULL OR TOTAL_MS >= 0))
);

CREATE INDEX DB2INTEL.IX_QUERY_AUDIT_CREATED ON DB2INTEL.QUERY_AUDIT (CREATED_AT);
CREATE INDEX DB2INTEL.IX_QUERY_AUDIT_STATUS  ON DB2INTEL.QUERY_AUDIT (STATUS, CREATED_AT);
CREATE INDEX DB2INTEL.IX_QUERY_AUDIT_SESSION ON DB2INTEL.QUERY_AUDIT (SESSION_ID, CREATED_AT);
CREATE INDEX DB2INTEL.IX_QUERY_AUDIT_SRC     ON DB2INTEL.QUERY_AUDIT (SOURCE_ID);

-- Human-verified question to SQL pairs (text only).
CREATE TABLE DB2INTEL.VERIFIED_QUERY (
    VERIFIED_ID      BIGINT        NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    SOURCE_ID        INTEGER       NOT NULL,
    QUESTION         VARCHAR(1000) NOT NULL,
    QUESTION_SHA256  CHAR(64)      NOT NULL,
    SQL_TEXT         CLOB(1M)      NOT NULL,
    ORIGIN_AUDIT_ID  BIGINT,
    VERIFIED_BY      VARCHAR(128)  NOT NULL DEFAULT USER,
    IS_ACTIVE        SMALLINT      NOT NULL DEFAULT 1,
    USE_COUNT        INTEGER       NOT NULL DEFAULT 0,
    CREATED_AT       TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    LAST_USED_AT     TIMESTAMP,
    CONSTRAINT PK_VERIFIED_QUERY PRIMARY KEY (VERIFIED_ID),
    CONSTRAINT UQ_VERIFIED_QUERY_Q UNIQUE (SOURCE_ID, QUESTION_SHA256),
    CONSTRAINT FK_VERIFIED_QUERY_SRC FOREIGN KEY (SOURCE_ID)
        REFERENCES DB2INTEL.DATA_SOURCE (SOURCE_ID) ON DELETE RESTRICT,
    CONSTRAINT FK_VERIFIED_QUERY_AUDIT FOREIGN KEY (ORIGIN_AUDIT_ID)
        REFERENCES DB2INTEL.QUERY_AUDIT (AUDIT_ID) ON DELETE SET NULL,
    CONSTRAINT CK_VERIFIED_QUERY_ACTIVE CHECK (IS_ACTIVE IN (0, 1)),
    CONSTRAINT CK_VERIFIED_QUERY_USES CHECK (USE_COUNT >= 0)
);

CREATE INDEX DB2INTEL.IX_VERIFIED_QUERY_AUDIT ON DB2INTEL.VERIFIED_QUERY (ORIGIN_AUDIT_ID);

-- One native Db2 VECTOR per (verified question, embedding model).
CREATE TABLE DB2INTEL.VERIFIED_QUERY_EMBEDDING (
    VERIFIED_ID      BIGINT        NOT NULL,
    EMBEDDING_MODEL  VARCHAR(64)   NOT NULL,
    EMBEDDING        VECTOR(768, FLOAT32) NOT NULL,
    CREATED_AT       TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_VERIFIED_QUERY_EMBEDDING PRIMARY KEY (VERIFIED_ID, EMBEDDING_MODEL),
    CONSTRAINT FK_VERIFIED_QUERY_EMB_VQ FOREIGN KEY (VERIFIED_ID)
        REFERENCES DB2INTEL.VERIFIED_QUERY (VERIFIED_ID) ON DELETE CASCADE
);

-- Audit rows record which verified example (if any) was reused.
ALTER TABLE DB2INTEL.QUERY_AUDIT
    ADD CONSTRAINT FK_QUERY_AUDIT_VERIFIED FOREIGN KEY (VERIFIED_ID_USED)
        REFERENCES DB2INTEL.VERIFIED_QUERY (VERIFIED_ID) ON DELETE SET NULL;

CREATE INDEX DB2INTEL.IX_QUERY_AUDIT_VERIFIED ON DB2INTEL.QUERY_AUDIT (VERIFIED_ID_USED);

-- User feedback, separate so QUERY_AUDIT is never updated.
CREATE TABLE DB2INTEL.QUERY_FEEDBACK (
    FEEDBACK_ID    BIGINT        NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
    AUDIT_ID       BIGINT        NOT NULL,
    RATING         SMALLINT      NOT NULL,
    CORRECTED_SQL  CLOB(1M),
    COMMENT_TEXT   VARCHAR(1000),
    CREATED_BY     VARCHAR(128)  NOT NULL DEFAULT USER,
    CREATED_AT     TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
    CONSTRAINT PK_QUERY_FEEDBACK PRIMARY KEY (FEEDBACK_ID),
    CONSTRAINT UQ_QUERY_FEEDBACK_AUDIT UNIQUE (AUDIT_ID),
    CONSTRAINT FK_QUERY_FEEDBACK_AUDIT FOREIGN KEY (AUDIT_ID)
        REFERENCES DB2INTEL.QUERY_AUDIT (AUDIT_ID) ON DELETE CASCADE,
    CONSTRAINT CK_QUERY_FEEDBACK_RATING CHECK (RATING IN (-1, 1))
);

-- Catalog documentation (SYSCAT.TABLES.REMARKS, max 254 bytes each).
COMMENT ON TABLE DB2INTEL.SCHEMA_MIGRATION         IS 'Db2 Intelligence: ledger of applied SQL migration scripts with SHA-256 checksums';
COMMENT ON TABLE DB2INTEL.APP_SETTING              IS 'Db2 Intelligence: runtime guardrail, retrieval and embedding settings';
COMMENT ON TABLE DB2INTEL.DATA_SOURCE              IS 'Db2 Intelligence: allow-list of database schemas the copilot may query read-only';
COMMENT ON TABLE DB2INTEL.SCHEMA_OBJECT            IS 'Db2 Intelligence: text descriptions of tables, views and columns harvested from SYSCAT';
COMMENT ON TABLE DB2INTEL.SCHEMA_EMBEDDING         IS 'Db2 Intelligence: VECTOR embeddings of schema object descriptions for semantic schema search';
COMMENT ON TABLE DB2INTEL.QUERY_AUDIT              IS 'Db2 Intelligence: append-only audit of every natural-language question, generated SQL and outcome';
COMMENT ON TABLE DB2INTEL.VERIFIED_QUERY           IS 'Db2 Intelligence: human-verified question to SQL examples';
COMMENT ON TABLE DB2INTEL.VERIFIED_QUERY_EMBEDDING IS 'Db2 Intelligence: VECTOR embeddings of verified questions for similarity lookup';
COMMENT ON TABLE DB2INTEL.QUERY_FEEDBACK           IS 'Db2 Intelligence: thumbs up or down feedback and corrected SQL for audited answers';

